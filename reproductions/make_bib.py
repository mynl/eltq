"""Write references.bib: the entries the pages here cite, extracted from a library.

The bibliography travels with the repository, so a clone renders without the
shared library. `references.bib` is generated, never edited by hand; an entry
is corrected in the library and the extract regenerated:

    uv run python make_bib.py <path to the shared .bib library>

Every ``@key`` in a ``.qmd`` beside this file is a citation unless it is a
Quarto cross-reference (``@tbl-``, ``@fig-``, ``@sec-``, ``@eq-``).
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CROSS_REFERENCE = ('tbl-', 'fig-', 'sec-', 'eq-')
CITATION = re.compile(r'(?<![\w.])@([A-Za-z][\w:-]*\w)')
ENTRY_START = re.compile(r'^@\w+\{([^,\s]+),', re.M)


def cited_keys():
    """Return the sorted citation keys used in the pages."""
    keys = set()
    for page in HERE.glob('*.qmd'):
        for key in CITATION.findall(page.read_text(encoding='utf-8')):
            if not key.startswith(CROSS_REFERENCE):
                keys.add(key)
    return sorted(keys)


def entries(library_text):
    """Return ``{key: entry text}`` for every entry in a .bib file, by brace matching."""
    found = {}
    for match in ENTRY_START.finditer(library_text):
        depth, i = 0, library_text.index('{', match.start())
        for j in range(i, len(library_text)):
            depth += {'{': 1, '}': -1}.get(library_text[j], 0)
            if depth == 0:
                found[match.group(1)] = library_text[match.start():j + 1]
                break
    return found


def main(library):
    keys = cited_keys()
    found = entries(Path(library).read_text(encoding='utf-8'))
    missing = [k for k in keys if k not in found]
    if missing:
        raise SystemExit(f'not in the library: {", ".join(missing)}')
    header = ('% Generated by make_bib.py from the shared library. Do not edit by hand;\n'
              '% correct the entry in the library and regenerate.\n\n')
    (HERE / 'references.bib').write_text(
        header + '\n\n'.join(found[k] for k in keys) + '\n', encoding='utf-8')
    print(f'references.bib: {len(keys)} entries ({", ".join(keys)})')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
